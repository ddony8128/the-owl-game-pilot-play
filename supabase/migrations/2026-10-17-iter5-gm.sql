-- 2026-10-17 Iteration 5 (GM 대시보드) — 운영 DB에 이미 적용됨(Management API). 새 DB에 한 번 실행한다. 여러 번 실행해도 안전.
--   rooms.reveal_result      : 마피아 결과 공개 토글(GM PATCH /api/gm/rooms { code, reveal_result })
--   game_state.timer_config  : 라운드/단계별 타이머 시간 { durations: {key: sec}, pending: {key: sec} }
--   gm_logs                  : GM 조작 기록(되돌리기·수동 보정·공개 토글·타이머 조정) — GM 전용
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS reveal_result BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE game_state ADD COLUMN IF NOT EXISTS timer_config JSONB NULL;

CREATE TABLE IF NOT EXISTS gm_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_code TEXT NOT NULL,
  game TEXT NULL,
  kind TEXT NOT NULL,
  content TEXT NOT NULL,
  meta JSONB NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS gm_logs_room_created_idx ON gm_logs (room_code, created_at DESC);

-- 2026-10-17 (후속) GM 조작 재전송 멱등 — 점수/현금/주식 ±1 의 request_id 를 gm_logs 가 선점한다. 운영 DB 적용됨.
ALTER TABLE gm_logs ADD COLUMN IF NOT EXISTS request_id TEXT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS gm_logs_room_request_key ON gm_logs (room_code, request_id) WHERE request_id IS NOT NULL;
