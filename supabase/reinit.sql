DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
GRANT USAGE, CREATE ON SCHEMA public TO postgres, anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO postgres, anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO postgres, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO postgres, anon, authenticated, service_role;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE players (
  id UUID NOT NULL DEFAULT gen_random_uuid(),
  nickname TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  feather INTEGER DEFAULT 0,
  PRIMARY KEY (id)
);

CREATE TABLE defense_monster_count (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  count INTEGER NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE mafia_stock_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  stock_key TEXT,
  round_number INTEGER NOT NULL,
  price_before INTEGER,
  price_after INTEGER,
  meta JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE mafia_phase_state (
  id INTEGER NOT NULL DEFAULT 1,
  round_number INTEGER NOT NULL,
  phase TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE mafia_player_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  player_id UUID,
  round_number INTEGER,
  phase TEXT,
  cash INTEGER,
  stocks JSONB,
  job TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE defense_score (
  player_id UUID NOT NULL,
  points INTEGER NOT NULL,
  PRIMARY KEY (player_id)
);

CREATE TABLE mafia_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  player_id UUID,
  round_number INTEGER NOT NULL,
  phase TEXT NOT NULL,
  action_type TEXT NOT NULL,
  payload JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE defense_monster_snapshot (
  instance_id UUID NOT NULL,
  monster_id INTEGER NOT NULL,
  round INTEGER NOT NULL,
  current_hp INTEGER NOT NULL,
  remaining_time INTEGER NOT NULL,
  slot_index INTEGER NOT NULL,
  PRIMARY KEY (instance_id, round)
);

CREATE TABLE gm_memos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE mafia_votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  round_number INTEGER,
  voter_id UUID,
  target_id UUID,
  vote_count INTEGER,
  unit_price INTEGER,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE defense_player_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  player_id UUID NOT NULL,
  round INTEGER NOT NULL,
  log TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE subway_player_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  player_id UUID,
  event_type TEXT NOT NULL,
  event_value JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE defense_score_snapshot (
  player_id UUID NOT NULL,
  round INTEGER NOT NULL,
  points INTEGER NOT NULL,
  PRIMARY KEY (player_id, round)
);

CREATE TABLE player_votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  voter_id UUID,
  topic TEXT,
  target_id UUID,
  reason TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE defense_card_state (
  player_id UUID NOT NULL,
  card_slot INTEGER NOT NULL,
  card_value INTEGER NOT NULL,
  is_active BOOLEAN NOT NULL,
  PRIMARY KEY (player_id, card_slot)
);

CREATE TABLE defense_phase_state (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  round BIGINT,
  PRIMARY KEY (id)
);

CREATE TABLE subway_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  player_id UUID,
  reporter_name TEXT NOT NULL,
  content TEXT NOT NULL,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT now(),
  decided_at TIMESTAMPTZ,
  PRIMARY KEY (id)
);

CREATE TABLE subway_player_state (
  player_id UUID NOT NULL,
  exit_number INTEGER DEFAULT 0,
  current_location TEXT,
  reset_count INTEGER DEFAULT 0,
  is_finished BOOLEAN DEFAULT false,
  finished_rank INTEGER,
  updated_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (player_id)
);

CREATE TABLE subway_play_records (
  id UUID NOT NULL DEFAULT gen_random_uuid(),
  session_id UUID NOT NULL,
  archived_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  player_id UUID,
  nickname TEXT,
  final_exit INTEGER,
  reset_count INTEGER,
  is_finished BOOLEAN,
  finished_rank INTEGER,
  clear_seconds INTEGER,
  total_moves INTEGER,
  correct_moves INTEGER,
  wrong_moves INTEGER,
  forward_moves INTEGER,
  back_moves INTEGER,
  too_fast_count INTEGER,
  rules_discovered INTEGER,
  rules_discovered_ids INTEGER[],
  reports_submitted INTEGER,
  wrong_by_reason JSONB,
  wrong_by_group JSONB,
  visit_by_group JSONB,
  PRIMARY KEY (id)
);

CREATE TABLE mafia_player_state (
  player_id UUID NOT NULL,
  cash INTEGER,
  is_mafia BOOLEAN DEFAULT false,
  job TEXT,
