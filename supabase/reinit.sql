  PRIMARY KEY (player_id)
);

CREATE TABLE mafia_stock_state (
  stock_key TEXT NOT NULL,
  price INTEGER NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (stock_key)
);

CREATE TABLE mafia_ability_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  player_id UUID,
  round_number INTEGER,
  phase TEXT,
  job TEXT,
  category TEXT,
  message TEXT NOT NULL,
  payload JSONB,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE game_state (
  id INTEGER NOT NULL DEFAULT 1,
  active_game TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now(),
  timer_start BOOLEAN,
  timer_start_at TIMESTAMPTZ,
  pause_at TIMESTAMPTZ,
  PRIMARY KEY (id)
);

CREATE TABLE rules_state (
  rule_key TEXT NOT NULL,
  is_open BOOLEAN DEFAULT false,
  updated_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (rule_key)
);

CREATE TABLE mafia_public_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  round_number INTEGER,
  phase TEXT,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE defense_monster_instance (
  id UUID NOT NULL,
  monster_id INTEGER NOT NULL,
  current_hp INTEGER NOT NULL,
  remaining_time INTEGER NOT NULL,
  slot_index INTEGER NOT NULL,
  status TEXT NOT NULL,
  spawned_round INTEGER NOT NULL,
  removed_round INTEGER,
  PRIMARY KEY (id)
);

CREATE TABLE defense_action (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  round INTEGER NOT NULL,
  player_id UUID NOT NULL,
  action_type TEXT NOT NULL,
  target_monster_id UUID,
  training_from INTEGER,
  training_to INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  rest_card TEXT,
  used_card_value BIGINT,
  PRIMARY KEY (id)
);

